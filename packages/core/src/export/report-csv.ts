import type { ReportLine } from '../domain/report-document.js';

export interface CsvOptions {
  /** Use `;` for locales with a decimal comma so spreadsheets split columns correctly. */
  delimiter: ',' | ';';
  decimalSeparator: '.' | ',';
}

/** Prevents spreadsheet applications from evaluating cell content as a formula. */
function neutralize(text: string): string {
  return /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
}

function quote(cell: string, delimiter: string): string {
  return /["\r\n]/.test(cell) || cell.includes(delimiter) ? `"${cell.replace(/"/g, '""')}"` : cell;
}

function numberCell(amount: number, decimalSeparator: string): string {
  return amount.toFixed(2).replace('.', decimalSeparator);
}

/** `safe` cells are generated by the renderer (numbers, operators) and never need formula neutralizing. */
interface Cell {
  text: string;
  safe: boolean;
}

function lineCells(line: ReportLine, options: CsvOptions): Cell[] | undefined {
  const text = (value: string): Cell => ({ text: value, safe: false });
  const safe = (value: string): Cell => ({ text: value, safe: true });
  const amountCell = (value: string, amount?: number): Cell =>
    amount === undefined ? text(value) : safe(numberCell(amount, options.decimalSeparator));

  switch (line.kind) {
    case 'title':
    case 'heading':
    case 'subheading':
    case 'subtitle':
    case 'note':
      return [text(line.text)];
    case 'row':
      return [text((line.level ? '  ' : '') + line.label), text(line.detail ?? ''), amountCell(line.value, line.amount)];
    case 'equation': {
      const cells: Cell[] = [];
      line.terms.forEach((term) => {
        if (term.op) {
          cells.push(safe(term.op));
        }
        cells.push(text(term.label), amountCell(term.value, term.amount));
      });
      cells.push(safe('='), text(line.result.label), amountCell(line.result.value, line.result.amount));
      return cells;
    }
  }
}

/** Renders the report document as CSV text with a UTF-8 byte order mark so spreadsheets detect the encoding. */
export function renderReportCsv(lines: readonly ReportLine[], options: CsvOptions): string {
  const rows: string[] = [];
  lines.forEach((line, index) => {
    if (line.kind === 'heading' && index > 0) {
      rows.push('');
    }
    const cells = lineCells(line, options);
    if (cells) {
      rows.push(cells.map((cell) => quote(cell.safe ? cell.text : neutralize(cell.text), options.delimiter)).join(options.delimiter));
    }
  });
  return `\uFEFF${rows.join('\r\n')}\r\n`;
}
